def split(text: str, sep: str = "|") -> list[str]:
    return [x.strip() for x in text.split(sep) if x.strip()]


# 每个岗位使用紧凑编码：
#   projects: 名称~目标~技术1/技术2/技术3~指标1;指标2~难点1;难点2，多条以 | 分隔
def P(pid, *, resp, tasks, skills, tools, scenes, projects, metrics, diffs,
      risks, dims, ladder, probes):
    plist = []
    for raw in split(projects):
        parts = [p.strip() for p in raw.split("~")]
        if len(parts) != 5:
            raise ValueError(f"{pid} 项目格式错误: {raw}")
        plist.append({
            "name": parts[0],
            "goal": parts[1],
            "tech_focus": split(parts[2], "/"),
            "typical_metrics": split(parts[3], ";"),
            "difficulties": split(parts[4], ";"),
        })
    dim_keys = [d.strip() for d in dims.split(",") if d.strip()]
    weights = [5, 4, 4, 3, 3, 2, 2, 2]
    dim_map = {k: weights[i] if i < len(weights) else 1 for i, k in enumerate(dim_keys)}
    return {
        "position_id": pid,
        "core_responsibilities": split(resp),
        "common_tasks": split(tasks),
        "core_skills": split(skills),
        "tools": split(tools),
        "business_scenarios": split(scenes),
        "project_types": plist,
        "achievement_metrics": split(metrics),
        "technical_difficulties": split(diffs),
        "work_risks": split(risks),
        "interview_dimensions": dim_map,
        "career_level_requirements": {
            k: {"scope": v} for k, v in zip(
                ["fresh", "junior", "mid", "senior", "expert"], split(ladder)
            )
        },
        "probe_topics": split(probes),
    }


