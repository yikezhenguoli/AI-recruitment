def main() -> None:
    pos_cfg = config.get_config("position_categories")
    order = pos_cfg["position_order"]
    cats = pos_cfg["categories"]
    by_id = {p["position_id"]: p for p in POSITIONS}
    assert len(by_id) == 30, f"知识库岗位数应为 30，实际 {len(by_id)}"
    assert set(by_id) == set(order), "知识库岗位与配置不一致: " + str(set(order) ^ set(by_id))

    out_dir = os.path.join(ROOT, "knowledge_base", "positions")
    os.makedirs(out_dir, exist_ok=True)
    index = []
    for pid in order:
        kb = dict(by_id[pid])
        meta = cats[pid]
        kb = {
            "position_id": pid,
            "index": meta["index"],
            "position_name": meta["name"],
            "family": meta["family"],
            **kb,
        }
        with open(os.path.join(out_dir, pid + ".json"), "w", encoding="utf-8") as fh:
            json.dump(kb, fh, ensure_ascii=False, indent=2)
        index.append({"position_id": pid, "index": meta["index"],
                      "name": meta["name"], "family": meta["family"],
                      "file": "knowledge_base/positions/" + pid + ".json"})

    common_dir = os.path.join(ROOT, "knowledge_base", "common")
    os.makedirs(common_dir, exist_ok=True)
    with open(os.path.join(common_dir, "common_banks.json"), "w", encoding="utf-8") as fh:
        json.dump(COMMON_BANKS, fh, ensure_ascii=False, indent=2)
    with open(os.path.join(common_dir, "position_index.json"), "w", encoding="utf-8") as fh:
        json.dump({"total": len(index), "positions": index}, fh, ensure_ascii=False, indent=2)

    print(f"[OK] 生成 {len(index)} 个岗位知识库 -> {out_dir}")
    for item in index[:3]:
        print("   ", item["index"], item["name"], item["file"])
    print("    ...")


